import Logger from "../../logger.js";

function migrateSqliteSnippetComments(db) {
  db.exec(`
    CREATE TABLE IF NOT EXISTS snippet_comments (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
      user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
      content TEXT NOT NULL,
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
      updated_at DATETIME DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_snippet_comments_snippet_created
      ON snippet_comments (snippet_id, created_at, id);
    CREATE INDEX IF NOT EXISTS idx_snippet_comments_user_id
      ON snippet_comments (user_id);
  `);
  Logger.info("Snippet comments migration completed");
}

async function migratePostgresSnippetComments(adapter) {
  await adapter.withClient(async (client) => {
    await client.query("BEGIN");
    try {
      await client.query("SELECT pg_advisory_xact_lock($1)", [1113150548]);
      await client.query(`
        CREATE TABLE IF NOT EXISTS snippet_comments (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
          user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
          content TEXT NOT NULL,
          created_at TIMESTAMP(0) DEFAULT (now() AT TIME ZONE 'utc'),
          updated_at TIMESTAMP(0) DEFAULT (now() AT TIME ZONE 'utc')
        )
      `);
      await client.query(`
        CREATE INDEX IF NOT EXISTS idx_snippet_comments_snippet_created
        ON snippet_comments (snippet_id, created_at, id)
      `);
      await client.query(`
        CREATE INDEX IF NOT EXISTS idx_snippet_comments_user_id
        ON snippet_comments (user_id)
      `);
      await client.query("COMMIT");
    } catch (error) {
      await client.query("ROLLBACK").catch(() => {});
      throw error;
    }
  });
  Logger.info("Snippet comments migration completed");
}

export { migrateSqliteSnippetComments, migratePostgresSnippetComments };
