import Logger from "../../logger.js";

function migrateSqliteRepliesAndNotifications(db) {
  db.exec("BEGIN");
  try {
    const columns = db.prepare("PRAGMA table_info(snippet_comments)").all();
    if (!columns.some((column) => column.name === "parent_comment_id")) {
      db.exec(`ALTER TABLE snippet_comments ADD COLUMN parent_comment_id INTEGER
        REFERENCES snippet_comments (id) ON DELETE CASCADE`);
    }
    db.exec(`
      CREATE TABLE IF NOT EXISTS notifications (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        recipient_user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
        actor_user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
        snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
        comment_id INTEGER NOT NULL REFERENCES snippet_comments (id) ON DELETE CASCADE,
        type TEXT NOT NULL CHECK (type IN ('comment', 'reply')),
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
        read_at DATETIME
      );
      CREATE INDEX IF NOT EXISTS idx_snippet_comments_parent_id
        ON snippet_comments (parent_comment_id);
      CREATE INDEX IF NOT EXISTS idx_notifications_recipient_created
        ON notifications (recipient_user_id, created_at DESC, id DESC);
    `);
    db.exec("COMMIT");
  } catch (error) {
    if (db.inTransaction) db.exec("ROLLBACK");
    throw error;
  }
  Logger.info("Comment replies and notifications migration completed");
}

async function migratePostgresRepliesAndNotifications(adapter) {
  await adapter.withClient(async (client) => {
    await client.query("BEGIN");
    try {
      await client.query("SELECT pg_advisory_xact_lock($1)", [1113150548]);
      await client.query(`
        ALTER TABLE snippet_comments ADD COLUMN IF NOT EXISTS parent_comment_id INTEGER
          REFERENCES snippet_comments (id) ON DELETE CASCADE
      `);
      await client.query(`
        CREATE TABLE IF NOT EXISTS notifications (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          recipient_user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
          actor_user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
          snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
          comment_id INTEGER NOT NULL REFERENCES snippet_comments (id) ON DELETE CASCADE,
          type TEXT NOT NULL CHECK (type IN ('comment', 'reply')),
          created_at TIMESTAMP(0) DEFAULT (now() AT TIME ZONE 'utc'),
          read_at TIMESTAMP(0)
        )
      `);
      await client.query(`
        CREATE INDEX IF NOT EXISTS idx_snippet_comments_parent_id
          ON snippet_comments (parent_comment_id)
      `);
      await client.query(`
        CREATE INDEX IF NOT EXISTS idx_notifications_recipient_created
          ON notifications (recipient_user_id, created_at DESC, id DESC)
      `);
      await client.query("COMMIT");
    } catch (error) {
      await client.query("ROLLBACK").catch(() => {});
      throw error;
    }
  });
  Logger.info("Comment replies and notifications migration completed");
}

export { migrateSqliteRepliesAndNotifications, migratePostgresRepliesAndNotifications };
