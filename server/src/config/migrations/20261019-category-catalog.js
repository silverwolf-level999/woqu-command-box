import Logger from "../../logger.js";

function migrateSqliteCategories(db) {
  const columns = db.prepare("PRAGMA table_info(categories)").all();
  if (columns.some((column) => column.name === "snippet_id")) {
    db.exec("BEGIN");
    try {
      db.exec(`
        ALTER TABLE categories RENAME TO categories_legacy;
        CREATE TABLE categories (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          name TEXT NOT NULL COLLATE NOCASE UNIQUE,
          color TEXT NOT NULL DEFAULT ''
        );
        CREATE TABLE snippet_categories (
          snippet_id INTEGER NOT NULL,
          category_id INTEGER NOT NULL,
          PRIMARY KEY (snippet_id, category_id),
          FOREIGN KEY (snippet_id) REFERENCES snippets (id) ON DELETE CASCADE,
          FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE CASCADE
        );
        INSERT OR IGNORE INTO categories (name)
          SELECT LOWER(TRIM(name)) FROM categories_legacy
          WHERE TRIM(name) <> '' ORDER BY id;
        INSERT OR IGNORE INTO snippet_categories (snippet_id, category_id)
          SELECT legacy.snippet_id, category.id
          FROM categories_legacy legacy
          JOIN categories category ON category.name = LOWER(TRIM(legacy.name))
          WHERE TRIM(legacy.name) <> '';
        DROP TABLE categories_legacy;
        CREATE INDEX IF NOT EXISTS idx_categories_name ON categories (name);
        CREATE INDEX IF NOT EXISTS idx_snippet_categories_category_id ON snippet_categories (category_id);
      `);
      db.exec("COMMIT");
      Logger.info("Category catalog migration completed");
    } catch (error) {
      if (db.inTransaction) db.exec("ROLLBACK");
      throw error;
    }
  } else {
    db.exec(`
      CREATE TABLE IF NOT EXISTS snippet_categories (
        snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
        category_id INTEGER NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
        PRIMARY KEY (snippet_id, category_id)
      );
      CREATE INDEX IF NOT EXISTS idx_snippet_categories_category_id ON snippet_categories (category_id);
    `);
  }
}

async function migratePostgresCategories(adapter) {
  await adapter.withClient(async (client) => {
    await client.query("BEGIN");
    try {
      await client.query("SELECT pg_advisory_xact_lock($1)", [1113150548]);
      const table = await client.query(`
        SELECT 1 FROM information_schema.tables
        WHERE table_schema = current_schema() AND table_name = 'categories'
      `);
      if (!table.rows.length) {
        await client.query("COMMIT");
        return;
      }
      const { rows } = await client.query(`
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'categories' AND column_name = 'snippet_id'
      `);
      if (rows.length) {
        await client.query("ALTER TABLE categories RENAME TO categories_legacy");
        await client.query(`
          CREATE TABLE categories (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            color TEXT NOT NULL DEFAULT ''
          )
        `);
        await client.query(`
          CREATE TABLE snippet_categories (
            snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
            category_id INTEGER NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
            PRIMARY KEY (snippet_id, category_id)
          )
        `);
        await client.query(`
          INSERT INTO categories (name)
            SELECT DISTINCT LOWER(BTRIM(name)) FROM categories_legacy
            WHERE BTRIM(name) <> ''
            ON CONFLICT DO NOTHING
        `);
        await client.query(`
          INSERT INTO snippet_categories (snippet_id, category_id)
            SELECT legacy.snippet_id, category.id
            FROM categories_legacy legacy
            JOIN categories category ON LOWER(category.name) = LOWER(BTRIM(legacy.name))
            WHERE legacy.snippet_id IS NOT NULL AND BTRIM(legacy.name) <> ''
            ON CONFLICT DO NOTHING
        `);
        await client.query("DROP TABLE categories_legacy CASCADE");
      }
      await client.query(`
        CREATE TABLE IF NOT EXISTS categories (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name TEXT NOT NULL,
          color TEXT NOT NULL DEFAULT ''
        )
      `);
      await client.query(`
        CREATE TABLE IF NOT EXISTS snippet_categories (
          snippet_id INTEGER NOT NULL REFERENCES snippets (id) ON DELETE CASCADE,
          category_id INTEGER NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
          PRIMARY KEY (snippet_id, category_id)
        )
      `);
      await client.query("ALTER TABLE categories ADD COLUMN IF NOT EXISTS color TEXT NOT NULL DEFAULT ''");
      await client.query("CREATE UNIQUE INDEX IF NOT EXISTS idx_categories_name_lower ON categories (LOWER(name))");
      await client.query("CREATE INDEX IF NOT EXISTS idx_snippet_categories_category_id ON snippet_categories (category_id)");
      await client.query("COMMIT");
    } catch (error) {
      await client.query("ROLLBACK").catch(() => {});
      throw error;
    }
  });
}

export { migrateSqliteCategories, migratePostgresCategories };
